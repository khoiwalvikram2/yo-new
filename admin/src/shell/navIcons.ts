/** Same normalisation the old IconRenderer used (IconRenderer.tsx:143). */
export function faKey(fa: string): string {
  return fa.trim().replace(/^fa-solid fa-/, '').replace(/^fa-/, '')
}

export function navIcon(fa: string | null | undefined): TablerIcon {
  if (!fa) return IconPoint
  const key = faKey(fa)
  return Object.hasOwn(NAV_ICONS, key) ? NAV_ICONS[key] : IconPoint
}
