/**
 * Nested RBAC: flat→nested backward compatibility for frontend.
 * Mirrors admin-backend hasPermission() so nav/guards work with nested requirements
 * when user has flat perms (e.g. sports.read grants sports.events.view).
 */

export type FlatGrant = { domain: string; action: string }

/** Flat permissions that grant a nested (domain, action). Keep in sync with admin-backend nestedPermissions.ts */
function getFlatPermissionsThatGrantNested(domain: string, action: string): FlatGrant[] {
  const key = `${domain}:${action}`
  return NESTED_TO_FLAT[key] ?? []
}

/**
 * Check if user has permission for (domain, action).
 * Same logic as backend: 1) all.*, 2) exact match, 3) flat grants nested.
 */
export function hasPermissionWithNested(
  userPerms: { domain: string; actions: string[] }[] | undefined,
  domain: string,
  action: string
): boolean {
  if (!userPerms?.length) return false
  const all = userPerms.find(p => p.domain === 'all')
  if (all && (all.actions.includes('*') || all.actions.includes(action))) return true
  const p = userPerms.find(p => p.domain === domain)
  if (p && (p.actions.includes(action) || p.actions.includes('*'))) return true
  if (domain.includes('.')) {
    for (const flat of getFlatPermissionsThatGrantNested(domain, action)) {
      const fp = userPerms.find(pp => pp.domain === flat.domain)
      if (fp && (fp.actions.includes(flat.action) || fp.actions.includes('*'))) return true
    }
  }
  return false
}

